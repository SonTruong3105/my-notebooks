"""CELL 6: Indexing & Slicing


"""

matrix = np.array([[10, 20, 30],
                   [40, 50, 60],
                   [70, 80, 90]])
# ============ INDEXING ============
# Lấy 1 phần tử duy nhất: matrix[hàng, cột]
print("matrix[1,1] =", matrix[1,1])   # Hàng 1, cột 1 → 50
print("matrix[2,0] =", matrix[2,0])   # Hàng 2, cột 0 → 70
# ============ SLICING ============
# Lấy mảng con: matrix[start:stop, start:stop]
# Lấy hàng 1 và 2, tất cả các cột → Shape (2, 3)
print("\nmatrix[1:3, 0:3]:\n", matrix[1:3, 0:3])
# Lấy toàn bộ cột 0 (3 hàng) → Mảng 1D [10, 40, 70]
print("\nmatrix[:3, 0]:\n", matrix[:3, 0])
# So sánh: Lấy cột 0 nhưng GIỮ dạng 2D → Shape (3, 1)
print("\nmatrix[:3, 0:1]:\n", matrix[:3, 0:1])
# Lấy hàng 1 (chỉ 1 hàng) → Shape (1, 3)
print("\nmatrix[1:2, 0:3]:\n", matrix[1:2, 0:3])

