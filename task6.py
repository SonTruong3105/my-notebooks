"""CELL 10: Dot Product

"""

A = np.array([[1, 2], [3, 4]])         # Ma trận 2x2
B = np.array([[5, 6], [7, 8]])         # Ma trận 2x2

print("np.dot(A, B):\n", np.dot(A, B)) # Nhân ma trận (cách 1)
print("\nA @ B:\n", A @ B)             # Nhân ma trận (cách 2 - toán tử @)
print("\nA * B (element-wise):\n", A * B)  # Nhân TỪNG PHẦN TỬ (khác với nhân ma trận)