"""CELL 8: Broadcasting"""

A = np.array ([[1,2,3],[4,5,6]]) # Shape (2, 3)
B = np.array ([10,20,30]) # Shape (3,) → tự động broadcast thành (1, 3) → (2, 3)
C = 50 # Scalar → broadcast thành (2, 3)
print("A + B: \n", A + B)  # Cộng từng cột với [10, 20, 30]
print("\nA + C \n", A + C) # Cộng tất cả phần tử với 100

